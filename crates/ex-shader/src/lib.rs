/// A diagnostic from I/O, native tools, standard validation or supported lowering.
#[derive(Debug)]
pub struct ShaderBuildError(String);
impl fmt::Display for ShaderBuildError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}
impl Error for ShaderBuildError {}
impl From<std::io::Error> for ShaderBuildError {
    fn from(value: std::io::Error) -> Self {
        Self(value.to_string())
    }
}
type Result<T> = std::result::Result<T, ShaderBuildError>;
fn fail(message: impl Into<String>) -> ShaderBuildError {
    ShaderBuildError(message.into())
}

/// A declared vec4 interface, in location order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Interface {
    pub name: String,
    pub location: u32,
}
/// A declared set-zero vec4 block. Slot and size map directly to EX bindings.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UniformBinding {
    pub name: String,
    pub binding: u32,
    pub minimum_bytes: u64,
}
/// Declared interfaces, uniform requirements and the actual lowered program size.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Reflection {
    pub stage: ShaderStage,
    pub inputs: Vec<Interface>,
    /// User locations only; vertex position is an additional mandatory output.
    pub outputs: Vec<Interface>,
    pub uniforms: Vec<UniformBinding>,
    pub instruction_count: usize,
}
impl Reflection {
    /// Deterministic JSON without an optional serialization dependency.
    pub fn to_json(&self) -> String {
        fn interfaces(values: &[Interface]) -> String {
            values
                .iter()
                .map(|v| {
                    format!(
                        "{{\"name\":{},\"location\":{},\"type\":\"vec4\"}}",
                        json_string(&v.name),
                        v.location
                    )
                })
                .collect::<Vec<_>>()
                .join(",")
        }
        let uniforms = self
            .uniforms
            .iter()
            .map(|v| {
                format!(
                    "{{\"name\":{},\"set\":0,\"binding\":{},\"minimum_bytes\":{}}}",
                    json_string(&v.name),
                    v.binding,
                    v.minimum_bytes
                )
            })
            .collect::<Vec<_>>()
            .join(",");
        format!("{{\"profile\":\"EX-GLSL-1\",\"stage\":{},\"inputs\":[{}],\"outputs\":[{}],\"vertex_position\":{},\"uniforms\":[{}],\"instruction_count\":{}}}", json_string(stage_name(self.stage)), interfaces(&self.inputs), interfaces(&self.outputs), self.stage == ShaderStage::Vertex, uniforms, self.instruction_count)
    }
}
fn json_string(s: &str) -> String {
    let mut result = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => result.push_str("\\\""),
            '\\' => result.push_str("\\\\"),
            c if c.is_control() => result.push_str(&format!("\\u{:04x}", c as u32)),
            c => result.push(c),
        }
    }
    result.push('"');
    result
}
pub(crate) fn stage_name(stage: ShaderStage) -> &'static str {
    match stage {
        ShaderStage::Vertex => "vertex",
        ShaderStage::Fragment => "fragment",
        ShaderStage::Compute => "compute",
    }
}

/// Owned validated EX instructions; descriptors borrow this module until creation.
#[derive(Debug, Clone)]
pub struct ShaderModule {
    label: String,
    reflection: Reflection,
    instructions: Vec<ShaderInstruction>,
    outputs: Vec<u32>,
}
impl ShaderModule {
    /// Device::create_shader copies this borrowed descriptor into regular EX state.
    pub fn descriptor(&self) -> ShaderDescriptor<'_> {
        ShaderDescriptor {
            label: &self.label,
            stage: self.reflection.stage,
            input_count: self.reflection.inputs.len() as u32,
            instructions: &self.instructions,
            outputs: &self.outputs,
        }
    }
    pub fn reflection(&self) -> &Reflection {
        &self.reflection
    }
    /// Rust source for include! in a module; no native shader tools needed at runtime.
    pub fn rust_source(&self) -> String {
        let ops = self
            .instructions
            .iter()
            .map(|op| format!("        ex::ShaderInstruction::{op:?},\n"))
            .collect::<String>();
        format!("// Generated by ex-shader EX-GLSL-1. Do not edit.\n// Reflection: {}\npub fn create(device: &ex::Device) -> Result<ex::Shader, ex::ShaderCreateError> {{\n    device.create_shader(ex::ShaderDescriptor {{\n        label: {:?},\n        stage: ex::ShaderStage::{:?},\n        input_count: {},\n        instructions: &[\n{}        ],\n        outputs: &{:?},\n    }})\n}}\n", self.reflection.to_json(), self.label, self.reflection.stage, self.reflection.inputs.len(), ops, self.outputs)
    }
}

pub(crate) fn path_error(path: &Path, error: impl fmt::Display) -> ShaderBuildError {
    fail(format!("{}: {error}", path.display()))
}
